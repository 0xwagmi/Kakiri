<script lang="ts">
  /**
   * The companion: a corner resident who reacts to the soundboard.
   *
   * Every state is derived from two booleans the page already has — is anything
   * playing, and is the library empty — so the backend needs no new events. A
   * slow tick recomputes the mood from timestamps, which keeps the transitions
   * declarative instead of a pile of setTimeout callbacks fighting each other.
   *
   *   wave ──(once, on launch)──▶ idle ⇄ idle_b
   *   idle ──playing────▶ dance ──(6 s of playing)────▶ listen
   *   quiet ──5 min──────▶ sit ──15 min──────▶ sleep
   *   empty library ─────▶ point
   *
   * Each state is one animated WebP with alpha baked in, all generated by
   * scripts/companion-assets.sh from clips of the same character and scaled to a
   * common reference, so she does not change size when the state changes.
   */
  import { onMount } from "svelte";
  import { fade } from "svelte/transition";

  import idle from "./assets/companion/idle.webp";
  import idleB from "./assets/companion/idle_b.webp";
  import listen from "./assets/companion/listen.webp";
  import dance from "./assets/companion/dance.webp";
  import wave from "./assets/companion/wave.webp";
  import point from "./assets/companion/point.webp";
  import sit from "./assets/companion/sit.webp";
  import sleep from "./assets/companion/sleep.webp";

  export let playing = false;
  /** the library has no sounds yet: she points at the empty grid */
  export let empty = false;

  type Mood = "wave" | "idle" | "idle_b" | "listen" | "dance" | "point" | "sit" | "sleep";
  const CLIP: Record<Mood, string> = {
    wave,
    idle,
    idle_b: idleB,
    listen,
    dance,
    point,
    sit,
    sleep,
  };

  const WAVE_MS = 5400;
  const LISTEN_AFTER_MS = 6000;
  const SIT_AFTER_MS = 5 * 60 * 1000;
  const SLEEP_AFTER_MS = 15 * 60 * 1000;
  const IDLE_SWAP_MS = 25 * 1000;
  const TICK_MS = 300;

  let mood: Mood = "wave";
  let launchedAt = Date.now();
  let playingSince: number | null = null;
  let quietSince = Date.now();

  // timestamps, not timers: the tick decides everything in one place
  $: if (playing && playingSince === null) {
    playingSince = Date.now();
  } else if (!playing && playingSince !== null) {
    playingSince = null;
    quietSince = Date.now();
  }

  function nextMood(now: number): Mood {
    if (now - launchedAt < WAVE_MS) return "wave";
    if (playing && playingSince !== null) {
      return now - playingSince > LISTEN_AFTER_MS ? "listen" : "dance";
    }
    const quiet = now - quietSince;
    if (quiet > SLEEP_AFTER_MS) return "sleep";
    if (quiet > SIT_AFTER_MS) return "sit";
    if (empty) return "point";
    return Math.floor(quiet / IDLE_SWAP_MS) % 2 === 0 ? "idle" : "idle_b";
  }

  onMount(() => {
    // the four states she can reach within seconds; the rest load on demand
    for (const src of [wave, idle, idleB, dance, listen]) new Image().src = src;
    const tick = setInterval(() => (mood = nextMood(Date.now())), TICK_MS);
    return () => clearInterval(tick);
  });
</script>

{#key mood}
  <img
    class="companion"
    src={CLIP[mood]}
    alt=""
    draggable="false"
    in:fade={{ duration: 130 }}
    out:fade={{ duration: 130 }}
  />
{/key}

